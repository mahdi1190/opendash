#!/usr/bin/env node
// tools/eb-bank-snapshot.mjs - write the bundled Enable Banking bank list
// (src/app/56-fin-eb-banks.js) that Connections uses for "Is my bank
// supported?" before the user has an Enable Banking app of their own
// (docs/dev/FINANCE_CONNECTIONS.md 2.3, Builder 4).
//
//   node tools/eb-bank-snapshot.mjs --app-id <uuid> --pem <key.pem> [--countries GB,IE,FI,...] [--out <file>] [--dry-run]
//   node tools/eb-bank-snapshot.mjs --fake [--out <file>]       (the test fake: no network)
//
// Reads GET /aspsps?country=<CC> with the maintainer's OWN application (a
// sandbox app is enough) through the read-only provider client, and writes
// ONLY public facts per bank: name, beta, maximum consent in days. No logos,
// BICs, ids or anything about any account. The key file is read from where
// it is and never copied. Run it before a release; the file says when.
//
// Exit codes: 0 written (or --dry-run printed), 1 bad arguments, 2 the API failed.

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { tmpdir } from 'node:os';
import { checkAppId, checkPem, ebClient, bankFromAspsp } from '../lib/fin-connect/enable-banking.mjs';
import { readOnlyClient } from '../lib/fin-connect/http.mjs';
import { allow } from '../lib/fin-connect/enable-banking.mjs';

const HERE = dirname(fileURLToPath(import.meta.url));
export const DEFAULT_OUT = join(HERE, '..', 'src', 'app', '56-fin-eb-banks.js');
// Enable Banking's markets (EEA + UK). Countries with no banks are left out of the file.
export const DEFAULT_COUNTRIES = ['GB', 'IE', 'FI', 'SE', 'NO', 'DK', 'EE', 'LV', 'LT', 'PL', 'DE', 'AT', 'NL', 'BE', 'LU', 'FR', 'ES', 'PT', 'IT', 'CZ', 'SK', 'SI', 'HR', 'HU', 'RO', 'BG', 'GR', 'CY', 'MT', 'IS', 'LI'];

function args(argv) {
  const a = { countries: DEFAULT_COUNTRIES, out: DEFAULT_OUT, dryRun: false, fake: false };
  for (let i = 0; i < argv.length; i++) {
    const k = argv[i];
    if (k === '--app-id') a.appId = argv[++i];
    else if (k === '--pem') a.pem = argv[++i];
    else if (k === '--countries') a.countries = String(argv[++i] || '').toUpperCase().split(',').filter(c => /^[A-Z]{2}$/.test(c));
    else if (k === '--out') a.out = resolve(argv[++i]);
    else if (k === '--dry-run') a.dryRun = true;
    else if (k === '--fake') a.fake = true;
    else if (k === '-h' || k === '--help') a.help = true;
    else throw new Error(`unknown argument ${k}`);
  }
  return a;
}

/** The file's text: one global the page reads (`FIN_EB_BANKS`), JSON inside so the server can read it too. */
export function snapshotSource(doc) {
  return '// src/app/56-fin-eb-banks.js - GENERATED by tools/eb-bank-snapshot.mjs; do not edit by hand.\n'
    + '// Enable Banking banks per country (public facts only: name, beta, maximum consent days),\n'
    + '// for "Is my bank supported?" before the user has an Enable Banking app. Once they do,\n'
    + '// Connections asks the live list instead (GET /api/fin-connect/eb/banks).\n'
    + `const FIN_EB_BANKS = ${JSON.stringify(doc, null, 1)};\n`;
}

/** Fetch every country's list -> {asOf, source, countries:{CC:[{name, beta?, maxConsentDays?}]}, counts}. */
export async function buildSnapshot({ appId, pem, countries = DEFAULT_COUNTRIES, fetchFn = globalThis.fetch, now = () => Date.now(), source = 'enable-banking' }) {
  const ctx = { now, log: () => {}, http: readOnlyClient(allow, { provider: 'enable-banking', fetchFn }) };
  const client = ebClient(ctx, { appId, pem });
  const out = {};
  for (const cc of countries) {
    const r = await client.call('GET', '/aspsps', { query: { country: cc } });
    const list = (Array.isArray(r.aspsps) ? r.aspsps : []).map(bankFromAspsp).filter(b => b && b.country === cc)
      .map(b => ({ name: b.name, ...(b.beta ? { beta: true } : {}), ...(b.maxConsentDays ? { maxConsentDays: b.maxConsentDays } : {}) }))
      .sort((x, y) => x.name.localeCompare(y.name));
    const seen = new Set();
    const uniq = list.filter(b => (seen.has(b.name) ? false : (seen.add(b.name), true)));
    if (uniq.length) out[cc] = uniq;
  }
  return { asOf: new Date(now()).toISOString().slice(0, 10), source, countries: out };
}

async function main() {
  let a;
  try { a = args(process.argv.slice(2)); } catch (e) { console.error(e.message); process.exit(1); }
  if (a.help) { console.log('node tools/eb-bank-snapshot.mjs --app-id <uuid> --pem <key.pem> [--countries GB,FI] [--out file] [--dry-run] | --fake'); return; }
  let fetchFn = globalThis.fetch, appId, pem, source = 'enable-banking';
  if (a.fake) {
    const { createFake, makeTestKey } = await import('../tests/fixtures/fin-fake-enablebanking.mjs');
    const fake = createFake({});
    const key = makeTestKey();
    appId = '00000000-0000-4000-8000-0000000000eb';
    fake.registerApp(appId, key.publicKey);
    fetchFn = fake.fetchFn; pem = key.pem; source = 'fake';
    if (a.out === DEFAULT_OUT && !a.dryRun) a.out = join(tmpdir(), 'opendash-eb-banks-fake.js');   // never overwrite the real file with fake banks
  } else {
    try { appId = checkAppId(a.appId); pem = checkPem(readFileSync(String(a.pem || ''), 'utf8')); }
    catch (e) { console.error(e.code === 'ENOENT' ? 'The --pem file was not found.' : e.message); process.exit(1); }
  }
  let doc;
  try { doc = await buildSnapshot({ appId, pem, countries: a.countries, fetchFn, source }); }
  catch (e) { console.error(`Enable Banking: ${e.message} (${e.code || 'error'})`); process.exit(2); }
  const counts = Object.fromEntries(Object.entries(doc.countries).map(([k, v]) => [k, v.length]));
  if (a.dryRun) { console.log(JSON.stringify({ asOf: doc.asOf, counts }, null, 1)); return; }
  mkdirSync(dirname(a.out), { recursive: true });
  writeFileSync(a.out, snapshotSource(doc));
  console.log(`wrote ${a.out}: ${Object.keys(counts).length} countries, GB ${counts.GB || 0} banks`);
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main();
